import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  console.error('Usage: node harness/sync.mjs [--check]');
  process.exit(2);
}
const check = args.includes('--check');
const files = {
  'AGENTS.md': `# Presentation harness — Codex and other agents

Read [harness/PROTOCOL.md](harness/PROTOCOL.md) before working in this repository.
It is the shared policy for Claude Code and GPT/Codex. Shared workflows are in
\`harness/skills/\`; Codex discovers their adapters in \`.agents/skills/\`.
Use the available tools for the requested operation.

<!-- Generated by node harness/sync.mjs; edit harness/PROTOCOL.md for shared policy. -->
`,
  'CLAUDE.md': `# Presentation harness — Claude Code

@harness/PROTOCOL.md

The imported file is the shared policy for Claude Code and GPT/Codex.
Shared workflows are in \`harness/skills/\`; adapters are in \`.claude/skills/\`.

<!-- Generated by node harness/sync.mjs; edit harness/PROTOCOL.md for shared policy. -->
`,
};

const skills = path.join(root, 'harness', 'skills');
for (const entry of fs.readdirSync(skills, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const name = entry.name;
  const source = fs.readFileSync(path.join(skills, name, 'SKILL.md'), 'utf8').replace(/\r\n/g, '\n');
  const front = source.match(/^---\n[\s\S]*?\n---(?:\n|$)/);
  if (!front) throw new Error(`Missing skill frontmatter: harness/skills/${name}/SKILL.md`);
  for (const provider of ['.agents', '.claude']) {
    files[`${provider}/skills/${name}/SKILL.md`] = `${front[0].trimEnd()}

<!-- Generated by node harness/sync.mjs; edit harness/skills/${name}/SKILL.md. -->
Read [the shared ${name} workflow](../../../harness/skills/${name}/SKILL.md) and follow it.
Paths inside that workflow are relative to the repository root. Preserve arguments
supplied with the skill invocation or in the conversation.
`;
  }
}

const differences = [];
for (const [name, content] of Object.entries(files)) {
  const file = path.join(root, name);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content) continue;
  differences.push(name);
  if (!check) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
console.log(JSON.stringify({ check, differences }));
if (check && differences.length) process.exitCode = 1;
